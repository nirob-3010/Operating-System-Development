// Console Mode State
static uint32_t* fb_addr = NULL;
static uint32_t  fb_width = 0;
static uint32_t  fb_height = 0;
static uint32_t  fb_pitch_pixels = 0;
static bool      has_framebuffer = false;

static volatile uint16_t* vga_text_buffer = (volatile uint16_t*)0xB8000;
static uint32_t cursor_x = 0;
static uint32_t cursor_y = 0;
static uint32_t max_cols = 80;
static uint32_t max_rows = 25;

#define COLOR_BG_DEFAULT    0x000F172A // Slate 900
#define COLOR_FG_DEFAULT    0x00F8FAFC // Slate 50
#define COLOR_TOPBAR        0x001E293B // Slate 800
#define COLOR_ACCENT        0x003B82F6 // Blue 500

static void fb_put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= fb_width || y >= fb_height || !fb_addr) return;
    fb_addr[y * fb_pitch_pixels + x] = color;
}

static void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    for (uint32_t cy = y; cy < y + h && cy < fb_height; cy++) {
        for (uint32_t cx = x; cx < x + w && cx < fb_width; cx++) {
            fb_addr[cy * fb_pitch_pixels + cx] = color;
        }
    }
}

static void fb_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t* glyph = font_8x16[c - 32];

    for (int row = 0; row < 16; row++) {
        uint8_t row_bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint32_t color = (row_bits & (0x80 >> col)) ? fg : bg;
            fb_put_pixel(x + col, y + row, color);
        }
    }
}

void console_clear(uint32_t color) {
    cursor_x = 0;
    cursor_y = 0;

    if (has_framebuffer && fb_addr) {
        for (uint32_t y = 0; y < fb_height; y++) {
            for (uint32_t x = 0; x < fb_width; x++) {
                fb_addr[y * fb_pitch_pixels + x] = color;
            }
        }
        // Draw elegant top bar
        fb_fill_rect(0, 0, fb_width, 24, COLOR_TOPBAR);
        // Draw top bar brand text
        const char* title = "NSK OS v0.3  |  x86-64 Long Mode Kernel  |  Linear Framebuffer";
        for (int i = 0; title[i] != '\0'; i++) {
            fb_draw_char(12 + i * 8, 4, title[i], 0x00E2E8F0, COLOR_TOPBAR);
        }
        cursor_y = 2; // Start text below top bar
    } else {
        // VGA text mode clear
        for (int i = 0; i < 80 * 25; i++) {
            vga_text_buffer[i] = (uint16_t)0x0720;
        }
    }
}

